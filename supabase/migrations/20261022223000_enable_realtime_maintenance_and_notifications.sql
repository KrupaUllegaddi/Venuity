-- Enable Realtime for core booking and venue tables
-- Adds maintenance_windows and notifications safely to supabase_realtime publication

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'maintenance_windows'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.maintenance_windows;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'notifications'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.notifications;
    END IF;
END $$;
